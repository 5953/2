static const int ZH_FONT_COUNT = (int)(sizeof(ZH_FONT) / sizeof(ZH_FONT[0]));

/* 按 UTF-8 三字节查字, 找不到返回 NULL */
static inline const char *const *zh_find(const char *utf8) {
    for (int i = 0; i < ZH_FONT_COUNT; i++) {
        if ((uint8_t)utf8[0] == (uint8_t)ZH_FONT[i].key[0] &&
            (uint8_t)utf8[1] == (uint8_t)ZH_FONT[i].key[1] &&
            (uint8_t)utf8[2] == (uint8_t)ZH_FONT[i].key[2])
            return ZH_FONT[i].row;
    }
    return NULL;
}